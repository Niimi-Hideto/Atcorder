#include <bits/stdc++.h>
using namespace std;

int main() {
    int n;
    cin >> n;

    // 上の桁（9桁目）から順に、n の x 桁目が 0 か 1 かを出力する
    // n >> x … n を右に x ビットずらして、x 桁目を一番下に持ってくる
    // & 1    … 一番下の1ビットだけ残す（0 か 1）
    // ビット演算は優先順位が低いので、全体を括弧で囲む
    for (int x = 9; x >= 0; x--) {
        cout << ((n >> x) & 1);
    }
    cout << endl;
}

